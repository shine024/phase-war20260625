"""批2a 文案换轴：声望→贡献（仅玩家可见文案与注释；信号名/函数名/存档键不动）"""
import io

fails = []


def rep(path, pairs):
    s = io.open(path, encoding='utf-8').read()
    for old, new in pairs:
        if old not in s:
            fails.append(path + " :: " + old[:36])
            continue
        s = s.replace(old, new)
    io.open(path, 'w', encoding='utf-8', newline='\n').write(s)


