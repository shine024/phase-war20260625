def http_json(url, payload=None, headers=None, timeout=120, method=None):
    data = None
    hdrs = {"User-Agent": "Mozilla/5.0"}
    if headers:
        hdrs.update(headers)
    if payload is not None:
        data = json.dumps(payload).encode("utf-8")
        hdrs.setdefault("Content-Type", "application/json")
    req = urllib.request.Request(url, data=data, headers=hdrs, method=method or ("POST" if data else "GET"))
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.status, json.loads(r.read().decode("utf-8", "ignore"))


def imgbb_upload(img_path, expiration=3600):
    """上传参考图到 imgbb, 返回直链 URL。image 字段支持 base64。"""
    with open(img_path, "rb") as f:
        b64 = base64.b64encode(f.read()).decode("ascii")
    body = urllib.parse.urlencode({
        "key": IMGBB_KEY,
        "image": b64,
        "expiration": str(expiration),
        "name": os.path.splitext(os.path.basename(img_path))[0],
    }).encode("ascii")
    req = urllib.request.Request(
        "https://api.imgbb.com/1/upload", data=body,
        headers={"Content-Type": "application/x-www-form-urlencoded"}, method="POST")
    with urllib.request.urlopen(req, timeout=120) as r:
        data = json.loads(r.read().decode("utf-8"))
    if not data.get("success"):
        raise RuntimeError("imgbb failed: " + json.dumps(data)[:300])
    return data["data"]["url"]


