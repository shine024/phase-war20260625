def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "upload":
        print(imgbb_upload(sys.argv[2]))
    elif cmd == "create":
        step_create(sys.argv[2], sys.argv[3])
    elif cmd == "poll":
        step_poll(sys.argv[2], sys.argv[3])
    elif cmd == "build":
        step_build(sys.argv[2], sys.argv[3])
    elif cmd == "pilot":
        step_create("ww2_tiger", "idle")
        step_poll("ww2_tiger", "idle")
        step_build("ww2_tiger", "idle")
        step_preview()
    elif cmd == "batch":
        jobs = [(u, a) for u, uc in UNITS.items() for a in uc["anims"]]
        # 第一遍: 全部建任务 (限流 6/min, 间隔 11s)
        for u, a in jobs:
            if os.path.exists(task_file(u, a)):
                print("[skip create] %s/%s 已有 task" % (u, a)); continue
            step_create(u, a); time.sleep(11)
        # 第二遍: 轮询+构建
        for u, a in jobs:
            mp4 = os.path.join(anim_dir(u, a), "source.mp4")
            if not os.path.exists(mp4):
                step_poll(u, a)
            step_build(u, a)
        step_preview()
    elif cmd == "preview":
        step_preview()
    elif cmd == "check":
        step_check()
    else:
        __doc__ and print(__doc__)


if __name__ == "__main__":
    main()
