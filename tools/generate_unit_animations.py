def step_build(unit, anim, raw_fps=8.0):
    adir = anim_dir(unit, anim)
    mp4 = os.path.join(adir, "source.mp4")
    raw_dir = anim_dir(unit, anim, "raw")
    for f in glob.glob(os.path.join(raw_dir, "*.png")):
        os.unlink(f)
    print("[%s/%s] ffmpeg 抽帧 fps=%s" % (unit, anim, raw_fps))
    subprocess.run([FFMPEG, "-y", "-loglevel", "error", "-i", mp4,
                    "-vf", "fps=%s" % raw_fps, os.path.join(raw_dir, "r%03d.png")], check=True)
    frames = sorted(glob.glob(os.path.join(raw_dir, "r*.png")))
    print("  raw frames: %d" % len(frames))

    from PIL import Image, ImageDraw, ImageFilter
    import numpy as np

    def alpha_of(path, luma_ref=None, sat_max=75, mn_floor=135, edge_mode=False):
        """白底→透明 v6c 主体连通域法(2026-08-29 定稿, cv2 加速版, 语义=v6):
        ① ok = 浅色低饱和(mn>=mn_floor 且 sat<=sat_max) —— 涵盖白底/暖灰框线/枪口烟云/脚下灰影
           (视频模型会给画面画一圈内嵌暖灰矩形框线 sat 55~70, 单一"纯白"思路全被它挡住)
        ② cv2连通域: ok 中 ⑴触碰画面边框 或 ⑵包含宽/高>=40px的纯白(mn>=240)长条 的组件 → 背景
           (纯白长条 = 内部白区种子, 框线隔开的两侧白都要杀; 封闭小白袋<40px保留防误抠)
        ③ keep候选 = 其余像素, 再取最大连通块(=单位本体), 框线环/烟岛/噪点出局
        ④ 脚线以下(实体最深行+4px)清扫; 边缘 1px 羽化; luma_ref 亮度校平
        踩坑记录(勿重蹈):
        - Pillow 12: Image.fromarray 的图 floodfill/getpixel 有缓冲别名问题; 且 PIL floodfill
          是纯 Python 实现(704² 要 5-10s), 全部改用 cv2.connectedComponents(C++, <100ms)
        - PIL floodfill thresh=0 不扩散到相邻等值像素; thresh 语义是"与种子色比对"非"相邻渐变"
        - 连通域面积统计: 每个组件必须独立编号再 count, 统一填同值会累计前面的"""
        import cv2
        im = Image.open(path).convert("RGB")
        arr = np.asarray(im)
        rgbv = arr.astype(np.int16)
        mn = rgbv.min(axis=2)
        sat = rgbv.max(axis=2) - rgbv.min(axis=2)
        h, w = mn.shape
        ok = ((mn >= mn_floor) & (sat <= sat_max)).astype(np.uint8)
        num, lab = cv2.connectedComponents(ok)
        kill = set()
        for edge in (lab[0, :], lab[-1, :], lab[:, 0], lab[:, -1]):
            kill |= set(np.unique(edge).tolist())
        kill.discard(0)
        # 纯白长条组件(>=40px 宽或高)所在的 ok 组件也是背景
        pw = ((mn >= 240) & (sat <= sat_max)).astype(np.uint8)
        n2, lab2, st2, _ = cv2.connectedComponentsWithStats(pw)
        for i in range(1, n2):
            x, y, bw2, bh2, area = st2[i]
            if max(bw2, bh2) >= 40:
                yy = int(y + bh2 // 2); xx = int(x + bw2 // 2)
                kill.add(int(lab[yy, xx]))
        kill.discard(0)
        killed = np.isin(lab, list(kill)) if kill else np.zeros((h, w), bool)
        keepc = ~killed
        if edge_mode:
            # v6e 边缘密封救援(仅白机身单位): 深色描边把白底挡在轮廓外,
            #   与边框隔离的密封区=候选主体(救回贴边白色部件/银白机身);
            #   副作用=深灰硝烟云也会连通, 故默认关闭走纯 v6c
            # v6e 边缘密封泛洪: 2D卡图自带深色轮廓线, Canny描边+膨胀成密封环,
            #   与边框连通的非边缘区=背景, 密封区内=候选主体(能救回贴边白色部件/银白机身)
            gray = cv2.cvtColor(arr, cv2.COLOR_RGB2GRAY)
            e = cv2.Canny(gray, 50, 150)
            e = cv2.dilate(e, np.ones((5, 5), np.uint8))
            nonedge = (e == 0).astype(np.uint8)
            nn, labn = cv2.connectedComponents(nonedge)
            border_n = set()
            for edge in (labn[0, :], labn[-1, :], labn[:, 0], labn[:, -1]):
                border_n |= set(np.unique(edge).tolist())
            border_n.discard(0)
            sealed = np.ones((h, w), bool)
            for ni in range(1, nn):
                if ni in border_n:
                    sealed &= ~(labn == ni)
            # 并集 → 最大连通块; 保险: 视频画暖灰框线时背景环会被密封, 若结果>45%画面
            #   判定泄漏, 回退纯色彩路径(v6c)
            union = (keepc | sealed).astype(np.uint8)
            n3, lab3, st3, _ = cv2.connectedComponentsWithStats(union)
            if n3 > 1:
                big = 1 + int(np.argmax(st3[1:, cv2.CC_STAT_AREA]))
                keep = lab3 == big
            else:
                keep = union.astype(bool)
            if keep.mean() > 0.45:
                n3, lab3, st3, _ = cv2.connectedComponentsWithStats(keepc.astype(np.uint8))
                if n3 > 1:
                    big = 1 + int(np.argmax(st3[1:, cv2.CC_STAT_AREA]))
                    keep = lab3 == big
                else:
                    keep = keepc
        else:
            union = keepc.astype(np.uint8)
            n3, lab3, st3, _ = cv2.connectedComponentsWithStats(union)
            if n3 > 1:
                big = 1 + int(np.argmax(st3[1:, cv2.CC_STAT_AREA]))
                keep = lab3 == big
            else:
                keep = keepc
        # v6d-2 边界可达近白修剪: 与画面边框经"近白路径(mn>=230,sat<=60)"连通的主体像素剔除
        #   —— 杀掉贴在主体上的白烟/残雾/亮斑; 被深色轮廓包住的白色部件不受影响;
        #      彩色火光(sat>60)受保护不会被误杀
        nw = ((mn >= 230) & (sat <= 60)).astype(np.uint8)
        nn2, labn2 = cv2.connectedComponents(nw)
        reach = set()
        for edge in (labn2[0, :], labn2[-1, :], labn2[:, 0], labn2[:, -1]):
            reach |= set(np.unique(edge).tolist())
        reach.discard(0)
        if reach:
            keep &= ~np.isin(labn2, list(reach))
        # 脚线清扫: 最深实体行(行内>=3实体像素)+4px 以下全透明
        row_solid = (keep.sum(axis=1) >= 3)
        if row_solid.any():
            keep[int(np.where(row_solid)[0].max()) + 4:, :] = False
        arrf = arr.astype(np.float32)
        if luma_ref is not None and keep.any() and not keep.all():
            cur = float(arrf[keep].mean())
            if cur > 1:
                gain = float(np.clip(luma_ref / cur, 0.92, 1.10))
                arrf = np.clip(arrf * gain, 0, 255)
        rgb = Image.fromarray(arrf.astype(np.uint8))
        alpha = Image.fromarray(np.where(keep, 255, 0).astype(np.uint8))
        alpha = alpha.filter(ImageFilter.GaussianBlur(0.8))
        return rgb, alpha

    def bbox_of(alpha):
        return alpha.getbbox()

    alphas = {}
    luma_ref = None
    unit_mn_floor = int(UNITS.get(unit, {}).get("mn_floor", 135))
    unit_edge = bool(UNITS.get(unit, {}).get("matte_edge", False))
    for p in frames:
        im, a = alpha_of(p, luma_ref, mn_floor=unit_mn_floor, edge_mode=unit_edge)
        if luma_ref is None:
            arr0 = np.asarray(im, dtype=np.float32)
            a0 = np.asarray(a) > 128
            if a0.any():
                luma_ref = float(arr0[a0].mean())
        alphas[p] = (im, a)

    # 全帧并集 bbox → 统一画幅防抖动
    u = None
    for _, a in alphas.values():
        b = bbox_of(a)
        if b is None:
            continue
        u = b if u is None else (min(u[0], b[0]), min(u[1], b[1]), max(u[2], b[2]), max(u[3], b[3]))
    if u is None:
        raise RuntimeError("所有帧都是空透明帧, 泛洪阈值可能不对")
    pad = 8
    u = (max(0, u[0] - pad), max(0, u[1] - pad), min(alphas[frames[0]][0].width, u[2] + pad), min(alphas[frames[0]][0].height, u[3] + pad))
    print("  union bbox: %s" % (u,))

    # 去重: 相邻帧缩略哈希距离
    def thumb_hash(a):
        return hashlib.md5(a.resize((16, 16)).tobytes()).hexdigest()
    distinct = []
    for p in frames:
        h = thumb_hash(alphas[p][1])
        if not distinct or h != distinct[-1][1]:
            distinct.append((p, h))
    print("  distinct frames: %d" % len(distinct))

    target = TARGET_FRAMES.get(anim, 8)
    idxs = [round(i * (len(distinct) - 1) / max(1, target - 1)) for i in range(target)]
    picked = [distinct[i][0] for i in dict.fromkeys(idxs)]

    # 合成 RGBA 统一缩放到画布 (脚底对齐 92% 高; 空中单位居中)
    air_units = ("mod_apache", "cold_boss_mig", "mod_apache_e", "fut_air_drone")
    foot_frac = 0.80 if (unit in air_units or bool(UNITS.get(unit, {}).get("air"))) else 0.92
    out_files = []
    for i, p in enumerate(picked):
        im, a = alphas[p]
        crop_im, crop_a = im.crop(u), a.crop(u)
        rgba = crop_im.convert("RGBA")
        rgba.putalpha(crop_a)
        bw, bh = rgba.size
        scale = min((CANVAS - 16) / bw, (CANVAS * foot_frac - 8) / bh)
        nw, nh = max(1, int(bw * scale)), max(1, int(bh * scale))
        rgba = rgba.resize((nw, nh), Image.LANCZOS)
        canvas = Image.new("RGBA", (CANVAS, CANVAS), (0, 0, 0, 0))
        canvas.paste(rgba, ((CANVAS - nw) // 2, int(CANVAS * foot_frac) - nh), rgba)
        fp = os.path.join(adir, "f%02d.png" % i)
        canvas.save(fp)
        out_files.append(os.path.basename(fp))
    print("  wrote %d frames" % len(out_files))

    # 雪碧图
    sheet = Image.new("RGBA", (CANVAS * len(out_files), CANVAS), (0, 0, 0, 0))
    for i, fn in enumerate(out_files):
        sheet.paste(Image.open(os.path.join(adir, fn)), (i * CANVAS, 0))
    sheet_path = os.path.join(adir, "sheet_%s.png" % anim)
    sheet.save(sheet_path)

    meta = {
        "unit": unit, "unit_name": UNITS[unit]["name"], "anim": anim,
        "frames": len(out_files), "frame_files": out_files,
        "canvas": CANVAS, "suggested_fps": 10 if anim == "attack" else 8,
        "foot_frac": foot_frac, "union_bbox": list(u),
        "model": MODEL, "mode": "keyframe",
        "source_video": "source.mp4", "generated_at": time.strftime("%Y-%m-%d %H:%M:%S"),
    }
    with open(os.path.join(adir, "meta.json"), "w", encoding="utf-8") as f:
        json.dump(meta, f, ensure_ascii=False, indent=1)
    print("  sheet: %s" % os.path.basename(sheet_path))


def step_check():
    """质检: ①朝向(列像素轮廓与参考卡正/镜像相关度) ②循环接缝 ③近白残留。"""
    from PIL import Image
    import numpy as np
    for unit, ucfg in UNITS.items():
        ref = np.asarray(Image.open(os.path.join(REF_DIR, ucfg["ref"])).convert("RGB"), dtype=np.float32)
        ref_mask = ref.min(axis=2) < 235
        ref_prof = ref_mask.sum(axis=1) * 0  # 占位, 实际用列轮廓
        ref_prof = ref_mask.sum(axis=0).astype(np.float32)
        ref_prof_n = ref_prof / max(1.0, ref_prof.sum())
        ref_mir_n = ref_prof_n[::-1]
        for anim in ucfg["anims"]:
            adir = anim_dir(unit, anim)
            fs = sorted(glob.glob(os.path.join(adir, "f*.png")))
            if not fs:
                continue
            arrs = [np.asarray(Image.open(p).convert("RGBA"), dtype=np.float32) for p in fs]
            stack = np.stack(arrs)
            alpha = stack[:, :, :, 3]
            facing = []
            for i in range(len(fs)):
                m = alpha[i] > 128
                prof = m.sum(axis=0).astype(np.float32)
                s = prof.sum()
                if s < 1:
                    facing.append(0.0)
                    continue
                prof_n = prof / s
                c_norm = float((prof_n * ref_prof_n).sum())
                c_mir = float((prof_n * ref_mir_n).sum())
                facing.append(1 if c_norm >= c_mir else -1)
            def diff(i, j):
                m = (alpha[i] > 128) & (alpha[j] > 128)
                return float(np.abs(stack[i, :, :, :3][m] - stack[j, :, :, :3][m]).mean()) if m.sum() else -1
            seam = diff(len(fs) - 1, 0)
            resid = 0.0
            for i in range(len(fs)):
                m = alpha[i] > 200
                if m.sum():
                    rgb = stack[i, :, :, :3][m]
                    resid = max(resid, float((rgb.min(axis=1) >= 240).mean() * 100))
            orient = "向左" if sum(facing) > 0 else ("向右!" if sum(facing) < 0 else "混合")
            print("%-10s/%-6s 朝向=%s(%d/%d帧左) 接缝=%.1f 残留%%=%.2f" % (
                unit, anim, orient, sum(1 for f in facing if f > 0), len(fs), seam, resid))


