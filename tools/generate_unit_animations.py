def download(url, path):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=300) as r, open(path, "wb") as f:
        while True:
            chunk = r.read(65536)
            if not chunk:
                break
            f.write(chunk)
    return os.path.getsize(path)


def find_video_url(obj):
    """在任务响应 JSON 里递归找 mp4 视频链接。"""
    hits = []
    def walk(o):
        if isinstance(o, dict):
            for k, v in o.items():
                if isinstance(v, str) and (".mp4" in v.lower() or v.startswith("http") and "video" in k.lower()):
                    hits.append((k, v))
                else:
                    walk(v)
        elif isinstance(o, list):
            for it in o:
                walk(it)
    walk(obj)
    return hits


